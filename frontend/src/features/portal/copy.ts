export function stateText(status: string | undefined, c: Record<keyof typeof en, string>) {
  switch (status) {
    case 'draft':
      return c.stateDraft;
    case 'published':
      return c.statePublished;
    case 'uploading':
      return c.stateUploading;
    case 'submitted':
      return c.stateSubmitted;
    case 'under_review':
      return c.stateReview;
    case 'reviewed':
      return c.stateReviewed;
    case 'resubmission_required':
      return c.stateResubmit;
    default:
      return '—';
  }
}
export const portalTranslations = { en, ar };
export function usePortalCopy() {
  const { i18n } = useTranslation();
  const arabic = i18n.resolvedLanguage === 'ar';
  return { c: arabic ? ar : en, arabic };
}
